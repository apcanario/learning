# ---------------------------------------------------------------- git state

def fetch():
    git('fetch', '-q', 'origin', '+refs/heads/main:refs/remotes/origin/main')


def upstream():
    return out('rev-parse', 'refs/remotes/origin/main')


def show(rev, path):
    """File bytes at rev:path, or None."""
    r = git('show', f'{rev}:{path}', check=False, binary=True)
    return r.stdout if r.returncode == 0 else None


def text(rev, path):
    b = show(rev, path)
    if b is None or b'\0' in b[:8000]:
        return None
    try:
        return b.decode('utf-8')
    except UnicodeDecodeError:
        return None


def is_ancestor(a, b):
    return git('merge-base', '--is-ancestor', a, b, check=False).returncode == 0


def rebase_dir():
    gd = pathlib.Path(out('rev-parse', '--absolute-git-dir'))
    return next((gd / d for d in ('rebase-merge', 'rebase-apply') if (gd / d).exists()), None)


def name_status(a, b):
    """[(status, old, new)] for a..b, renames detected."""
    raw = git('diff', '--name-status', '-z', '-M', a, b).stdout.split('\0')
    res, i = [], 0
    while i < len(raw) and raw[i]:
        st = raw[i]
        if st[0] in 'RC':
            res.append((st[0], raw[i + 1], raw[i + 2])); i += 3
        else:
            res.append((st[0], raw[i + 1], raw[i + 1])); i += 2
    return res


def changed(a, b):
    return [p for p in git('diff', '--name-only', '-z', a, b).stdout.split('\0') if p]


def marker_files(paths=None):
    """Tracked text files with conflict markers at line start (working tree)."""
    args = ['grep', '-I', '-l', '-E', f'^({M_OPEN}|{M_CLOSE})( |$)']
    r = git(*args, *(['--', *paths] if paths else []), check=False)
    return sorted(set(r.stdout.split())) if r.returncode == 0 else []


def subjects(a, b):
    return [ln for ln in out('log', '--format=%h %s', f'{a}..{b}').splitlines() if ln]


# ---------------------------------------------------------------- the lock

def read_lock(rev):
    b = show(rev, LOCK)
    if b is None:
        return None
    try:
        lk = json.loads(b)
    except ValueError:
        lk = {'row': '?', 'note': 'unreadable lock file'}
    try:
        t = datetime.datetime.fromisoformat(lk['utc'])
    except (KeyError, TypeError, ValueError):
        t = datetime.datetime.fromtimestamp(int(out('log', '-1', '--format=%ct', rev, '--', LOCK) or 0),
                                            datetime.timezone.utc)
    lk['_age_min'] = (now() - t).total_seconds() / 60
    return lk


def commit_on(parent, files, msg):
    """A commit on parent changing only `files` (path -> bytes, None to delete), built in a temporary index."""
    idx = ROOT / '.git' / f'land-index-{os.getpid()}'
    env = {'GIT_INDEX_FILE': str(idx)}
    try:
        git('read-tree', parent, env=env)
        for p, data in files.items():
            if data is None:
                git('update-index', '--force-remove', p, env=env)
            else:
                blob = git('hash-object', '-w', '--stdin', inp=data, binary=True).stdout.decode().strip()
                git('update-index', '--add', '--cacheinfo', f'100644,{blob},{p}', env=env)
        tree = git('write-tree', env=env).stdout.strip()
        return git('commit-tree', tree, '-p', parent, '-m', msg).stdout.strip()
    finally:
        idx.unlink(missing_ok=True)


def push(rev):
    r = git('push', '-q', 'origin', f'{rev}:refs/heads/main', check=False)
    return r.returncode == 0, (r.stderr.strip().splitlines() or [''])[-1]


class Lock:
    def __init__(self, row, opts):
        self.row, self.o = row, opts
        self.token = uuid.uuid4().hex
        # this clone's last token for the row (a crashed run's lock is ours); kept in .git, never in a tracked file
        self.mine = pathlib.Path(out('rev-parse', '--absolute-git-dir')) / 'land' / f'{row}-lock.json'
        self.held = False
        self.took_over = None

    def ours(self, lk):
        if lk.get('token') == self.token:
            return True
        try:
            prev = json.loads(self.mine.read_text())['token']
        except (OSError, ValueError, KeyError):
            return False
        if lk.get('token') == prev and lk.get('row') == self.row:
            self.token = prev
            return True
        return False

    def acquire(self):
        deadline = time.time() + self.o.wait_minutes * 60
        last_note = 0
        while True:
            fetch()
            tip = upstream()
            lk = read_lock(tip)
            if lk and self.ours(lk):
                self.held = True
                say(f'lock already ours (row {self.row}, from an earlier run in this clone)')
                return
            if lk and lk['_age_min'] < self.o.stale_minutes:
                if time.time() > deadline:
                    raise Timeout(f"lock held by row {lk.get('row')} ({lk.get('host')}) for {lk['_age_min']:.0f} min; "
                                  f'waited {self.o.wait_minutes:g} min')
                if time.time() - last_note > 300 or not last_note:
                    say(f"waiting: lock held by row {lk.get('row')} ({lk.get('host')}), "
                        f"{lk['_age_min']:.1f} min old; polling every {self.o.poll_seconds:g} s")
                    last_note = time.time()
                time.sleep(self.o.poll_seconds)
                continue
            body = {'row': self.row, 'utc': now().isoformat(timespec='seconds'), 'host': socket.gethostname(),
                    'pid': os.getpid(), 'token': self.token}
            msg = f'land {self.row}: lock'
            if lk:
                self.took_over = {k: lk.get(k) for k in ('row', 'utc', 'host')} | {'age_min': round(lk['_age_min'], 1)}
                body['took_over'] = self.took_over
                msg += f" (stale lock of row {lk.get('row')}, {lk['_age_min']:.0f} min old, taken over)"
            sha = commit_on(tip, {LOCK: (json.dumps(body, indent=1) + '\n').encode()}, msg)
            ok, err = push(sha)
            if ok:
                self.held = True
                self.mine.parent.mkdir(parents=True, exist_ok=True)
                self.mine.write_text(json.dumps({'token': self.token, 'utc': body['utc']}) + '\n')
                say(f'lock taken ({sha[:9]})' + (f" after taking over the stale lock of row {lk.get('row')}" if lk else ''))
                return
            if time.time() > deadline:
                raise Timeout(f'could not take the lock in {self.o.wait_minutes:g} min (last push: {err})')
            time.sleep(random.uniform(*self.o.jitter))

    def release(self):
        if not self.held:
            return 'not held'
        for _ in range(8):
            try:
                fetch()
                tip = upstream()
                lk = read_lock(tip)
                if not lk or lk.get('token') != self.token:
                    self.held = False
                    return 'already gone' if not lk else f"not ours any more (row {lk.get('row')} holds it)"
                ok, err = push(commit_on(tip, {LOCK: None}, f'land {self.row}: unlock'))
                if ok:
                    self.held = False
                    say('lock released')
                    return 'released'
            except Stop as e:
                err = e.what
            time.sleep(random.uniform(*self.o.jitter))
        say(f'LOCK NOT RELEASED ({err}); run: python3 kit/land.py unlock {self.row}')
        return 'NOT released'


