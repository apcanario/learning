class Unresolvable(Exception):
    pass


class Ctx:
    """What the automatic resolutions did: notes for a human (out/<row>/land-notes.md) and the upstream lines an
    automatic merge rewrote on purpose (the preservation check counts them as preserved)."""
    def __init__(self, row):
        self.row, self.notes, self.superseded, self.regen_rows = row, [], set(), set()

    def note(self, text):
        self.notes.append(f'## {now().isoformat(timespec="seconds")}\n\n{text}\n\n')

    def flush(self):
        # written after the run (not during the rebase, which needs a clean tree)
        if self.notes:
            f = rowdir(self.row) / 'land-notes.md'
            f.parent.mkdir(parents=True, exist_ok=True)
            with f.open('a', encoding='utf-8') as fh:
                fh.write(''.join(self.notes))


def ops(a, b):
    return difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes()


def changes(base, side):
    return [(i1, i2, side[j1:j2]) for t, i1, i2, j1, j2 in ops(base, side) if t != 'equal']


def apply(base, lo, hi, chs):
    res, i = [], lo
    for i1, i2, new in chs:
        res += base[i:i1] + new
        i = i2
    return res + base[i:hi]


def merge3(base, up, our, resolve):
    """3-way merge of sequences; a region both sides changed goes to resolve(base_slice, up_slice, our_slice)."""
    allc = sorted([(c, 'u') for c in changes(base, up)] + [(c, 'o') for c in changes(base, our)],
                  key=lambda x: (x[0][0], x[0][1]))
    clusters = []
    for c, side in allc:
        if clusters and c[0] <= clusters[-1]['hi']:
            cl = clusters[-1]
            cl['hi'] = max(cl['hi'], c[1]); cl[side].append(c)
        else:
            clusters.append({'lo': c[0], 'hi': c[1], 'u': [c] if side == 'u' else [], 'o': [c] if side == 'o' else []})
    res, i = [], 0
    for cl in clusters:
        res += base[i:cl['lo']]
        u = apply(base, cl['lo'], cl['hi'], cl['u'])
        o = apply(base, cl['lo'], cl['hi'], cl['o'])
        if not cl['o']:
            res += u
        elif not cl['u'] or u == o:
            res += o
        else:
            res += resolve(base[cl['lo']:cl['hi']], u, o)
        i = cl['hi']
    return res + base[i:]


def only_adds(base, side):
    return all(t in ('equal', 'insert') for t, *_ in ops(base, side))


def union_resolver(ours_first=False):
    """Both sides only inserted into b: keep both insertions (theirs then ours; ours first for a newest-first log),
    an identical non-blank line inserted by both kept once."""
    def resolve(b, u, o):
        if not (only_adds(b, u) and only_adds(b, o)):
            raise Unresolvable('a side removed or changed a line here (union applies only when both sides insert)')
        iu = {i1: new for i1, _, new in changes(b, u)}
        io = {i1: new for i1, _, new in changes(b, o)}
        res = []
        for i in range(len(b) + 1):
            x, y = iu.get(i, []), io.get(i, [])
            seen = {l for l in x if l.strip()}
            y = [l for l in y if not (l.strip() and l in seen)]
            res += (y + x) if ours_first else (x + y)
            if i < len(b):
                res.append(b[i])
        return res
    return resolve


def strict_resolver(b, u, o):
    raise Unresolvable('both sides changed the same lines')


# -- BACKLOG: records keyed by row id (a record runs from "| <id> |" to the line that closes its last cell)

NEXT_UP = '__next_up__'


def row_key(line):
    s = line.strip()
    if s.startswith('Next up:'):
        return NEXT_UP
    if not s.startswith('|'):
        return None
    cell = s.strip('|').split('|')[0].strip()
    if not cell or set(cell) <= set('-: ') or cell in ('#', 'Row', 'Date', 'Code'):
        return None
    return cell


def units(lines):
    """BACKLOG lines grouped into units: a table record (possibly several lines) or a single other line."""
    res, i = [], 0
    while i < len(lines):
        j = i
        if row_key(lines[i]) not in (None, NEXT_UP):
            while j < len(lines) - 1 and not lines[j].rstrip().endswith('|'):
                j += 1
        res.append(''.join(lines[i:j + 1]))
        i = j + 1
    return res


def first_cells(unit):
    return unit.split('\n', 1)[0].split(' | ')[:3]


def keyed_resolver(ctx):
    def resolve(b, u, o):
        def keyed(us):
            d = {}
            for x in us:
                k = row_key(x)
                if k is not None:
                    if k in d:
                        raise Unresolvable(f'row {k} appears twice')
                    d[k] = x
            return d
        free_u = [x for x in u if row_key(x) is None and x.strip()]
        free_o = [x for x in o if row_key(x) is None and x.strip()]
        if free_u != free_o:
            raise Unresolvable('prose lines changed on both sides inside a table region: '
                               + '; '.join(x.strip()[:80] for x in (free_u + free_o)[:2]))
        B, U, O = keyed(b), keyed(u), keyed(o)
        res = {}
        for k in B.keys() | U.keys() | O.keys():
            bv, uv, ov = B.get(k), U.get(k), O.get(k)
            if uv == ov:
                res[k] = uv
            elif uv == bv:
                res[k] = ov
            elif ov == bv:
                res[k] = uv
            elif k == NEXT_UP and uv and ov:
                res[k] = uv
                say('BACKLOG "Next up" line rewritten on both sides: upstream\'s kept, ours saved in '
                    f'out/{ctx.row}/land-notes.md for a human to reconcile')
                ctx.note(f'docs/BACKLOG.md "Next up": upstream\'s line was kept. Ours was:\n\n{ov.rstrip()}\n\n'
                         f'Upstream\'s:\n\n{uv.rstrip()}')
            elif bv and uv and ov and first_cells(uv) == first_cells(bv) == first_cells(ov):
                # both sides changed only the row's prompt cell (each re-saved it): upstream's for now, regenerated from
                # the merged tree after the rebase (resave_prompts)
                res[k] = uv
                ctx.regen_rows.add(k)
                say(f'BACKLOG row {k}: prompt cell changed on both sides: regenerated after the merge; ours saved in '
                    f'out/{ctx.row}/land-notes.md')
                ctx.note(f'docs/BACKLOG.md row {k}: prompt cell changed on both sides; regenerated by next_prompt.py '
                         f'on the merged tree. Ours was:\n\n{ov.rstrip()}')
            elif bv and (uv is None or ov is None) and first_cells(uv or bv) == first_cells(ov or bv):
                # one side closed (removed) the row, the other only refreshed its prompt cell: the removal stands
                res[k] = None
                kept = ov if uv is None else uv
                say(f'BACKLOG row {k}: removed by one side, prompt changed by the other: removed; the changed record '
                    f'is in out/{ctx.row}/land-notes.md')
                ctx.note(f'docs/BACKLOG.md row {k} was removed by {"upstream" if uv is None else "us"}; the other '
                         f'side had changed its prompt cell to:\n\n{kept.rstrip()}')
            else:
                raise Unresolvable(f'row {k} changed on both sides:\n    upstream: {(uv or "(removed)").strip()[:160]}'
                                   f'\n    ours:     {(ov or "(removed)").strip()[:160]}')
        out_, placed = [], set()
        for x in u:
            k = row_key(x)
            if k is None:
                out_.append(x)
            elif res.get(k):
                out_.append(res[k]); placed.add(k)
        prev = None
        for x in o:
            k = row_key(x)
            if k is None:
                continue
            if res.get(k) and k not in placed:
                pos = next((n + 1 for n, y in enumerate(out_) if prev and row_key(y) == prev), None)
                if pos is None:
                    pos = next((n for n, y in enumerate(out_) if row_key(y) not in (None, NEXT_UP)), len(out_))
                out_.insert(pos, res[k]); placed.add(k)
            if k in placed:
                prev = k
        return out_
    return resolve


# -- structured literals: TOML arrays (`key = [`) and Python module constants (`NAME = (`, `[`, `{`)

LIT_RE = {'toml': re.compile(r'^[ \t]*([A-Za-z0-9_.\-"]+)[ \t]*=[ \t]*(\[)', re.M),
          'py': re.compile(r'^([A-Z][A-Z0-9_]*)[ \t]*=[ \t]*([\[\(\{])', re.M)}
CLOSE = {'[': ']', '(': ')', '{': '}'}


def scan(t, i, stop_at_comma=False):
    """From t[i] (an opening bracket) to its closing bracket, skipping strings and comments; returns the index of the
    closing bracket and the top-level comma positions."""
    depth, commas, n = 0, [], len(t)
    while i < n:
        c = t[i]
        if c == '#':
            while i < n and t[i] != '\n':
                i += 1
            continue
        if c in '"\'':
            q = t[i:i + 3] if t[i:i + 3] in ('"""', "'''") else c
            j = i + len(q)
            while j < n and t[j:j + len(q)] != q:
                j += 2 if (t[j] == '\\') else 1
            i = j + len(q)
            continue
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                return i, commas
        elif c == ',' and depth == 1:
            commas.append(i)
        i += 1
    return None, commas


def literals(t, kind):
    """{id: (open, close)} of every top-level literal assignment; id = name#occurrence."""
    res, seen = {}, collections.Counter()
    for m in LIT_RE[kind].finditer(t):
        o = m.start(2)
        c, _ = scan(t, o)
        if c is None:
            continue
        seen[m.group(1)] += 1
        res[f'{m.group(1)}#{seen[m.group(1)]}'] = (o, c)
    return res


def elements(t, o, c):
    """[(start, end)] of the stripped element texts between brackets t[o] and t[c]."""
    _, commas = scan(t, o)
    cuts = [o] + [x for x in commas if x < c] + [c]
    res = []
    for a, b in zip(cuts, cuts[1:]):
        s, e = a + 1, b
        while s < e and t[s] in ' \t\r\n':
            s += 1
        while e > s and t[e - 1] in ' \t\r\n':
            e -= 1
        if s < e:
            res.append((s, e))
    return res


def elem_key(raw, kind, opener):
    try:
        if kind == 'toml':
            v = tomllib.loads('x = [\n' + raw + '\n]')['x'][0]
        elif opener == '{':
            v = list(ast.literal_eval('{\n' + raw + '\n}').items())[0]
        else:
            v = ast.literal_eval('[\n' + raw + '\n]')[0]
    except Exception as e:
        raise Unresolvable(f'element is not a plain literal: {raw[:60]!r} ({e.__class__.__name__})')
    return json.dumps(v, sort_keys=True, default=repr)


def merge_literal(tb, tu, to, spans, kind):
    """Merge one literal (spans: (open, close) in b, u, o; None where absent) as data."""
    (sb, su, so) = spans
    opener = tu[su[0]]
    def items(t, sp):
        return [(t[s:e], elem_key(t[s:e], kind, opener)) for s, e in elements(t, *sp)] if sp else []
    B, U, O = items(tb, sb), items(tu, su), items(to, so)
    if [k for _, k in U] == [k for _, k in O]:
        return tu[su[0]:su[1] + 1]
    bk, uk, ok = ({k for _, k in X} for X in (B, U, O))
    if opener == '{':   # dict: three-way by key
        def kv(X):
            return {json.dumps(json.loads(k)[0]): (r, k) for r, k in X}
        Bd, Ud, Od = kv(B), kv(U), kv(O)
        res = []
        for key in list(Ud) + [x for x in Od if x not in Ud]:
            b_, u_, o_ = (D.get(key, (None, None))[1] for D in (Bd, Ud, Od))
            if u_ == o_ or o_ == b_:
                pick = Ud.get(key)
            elif u_ == b_:
                pick = Od.get(key)
            else:
                raise Unresolvable(f'key {key} changed on both sides')
            if pick:
                res.append(pick[0])
    else:               # list or array: (base ∩ ours ∩ theirs) ∪ ours-added ∪ theirs-added, theirs' order
        res = [r for r, k in U if k not in bk or k in ok]
        keys = [k for r, k in U if k not in bk or k in ok]
        prev = None
        for r, k in O:
            if k not in bk and k not in uk and k not in keys:
                pos = keys.index(prev) + 1 if prev in keys else len(keys)
                while pos < len(keys) and keys[pos] not in bk and keys[pos] not in ok:   # ours after theirs' insertions
                    pos += 1
                res.insert(pos, r); keys.insert(pos, k)
            if k in keys:
                prev = k
    el = elements(tu, *su)
    inner = tu[su[0] + 1:su[1]]
    if el:
        prefix, suffix = tu[su[0] + 1:el[0][0]], tu[el[-1][1]:su[1]]
        sep = tu[el[0][1]:el[1][0]] if len(el) > 1 else (',' + prefix if '\n' in prefix else ', ')
    else:
        prefix, suffix, sep = ('\n  ', ',\n', ',\n  ') if '\n' in inner else ('', '', ', ')
    if opener == '(' and len(res) == 1 and not suffix.lstrip().startswith(','):
        suffix = ',' + suffix
    body = prefix + sep.join(res) + suffix if res else ''
    return tu[su[0]] + body + tu[su[1]]


def structured_merge(b, u, o, kind, ctx, path):
    """Mask every literal, merge the rest (TOML: add-only union; Python: no both-side change allowed), then merge the
    literals as data and put them back."""
    L = [literals(t, kind) for t in (b, u, o)]
    def mask(t, lit):
        for lid, (s, e) in sorted(lit.items(), key=lambda x: -x[1][0]):
            t = t[:s] + f'\0{lid}\0' + t[e + 1:]
        return t
    mb, mu, mo = (mask(t, l).splitlines(keepends=True) for t, l in zip((b, u, o), L))
    merged = ''.join(merge3(mb, mu, mo, union_resolver() if kind == 'toml' else strict_resolver))
    def fill(m):
        lid = m.group(1)
        sb, su, so = (l.get(lid) for l in L)
        if su and so:
            return merge_literal(b, u, o, (sb, su, so), kind)
        t, s = (u, su) if su else (o, so)
        return t[s[0]:s[1] + 1]
    return re.sub(r'\0([^\0]+)\0', fill, merged)


# -- validation of a merged file

def cells(line):
    s = re.sub(r'`[^`]*`', '', line.strip())
    return len(re.findall(r'(?<!\\)\|', s))


def bad_rows(lines):
    bad, n0 = set(), None
    for ln in lines:
        if ln.lstrip().startswith('|'):
            if n0 is None:
                n0 = cells(ln)
            elif ln.rstrip().endswith('|') and cells(ln) != n0:
                bad.add(ln.strip())
        else:
            n0 = None
    return bad


def validate(path, merged, u, o):
    if path.endswith('.toml'):
        try:
            tomllib.loads(merged)
        except tomllib.TOMLDecodeError as e:
            raise Unresolvable(f'merged file does not parse as TOML: {e}')
    elif path.endswith('.py'):
        try:
            compile(merged, path, 'exec'); ast.parse(merged)
        except SyntaxError as e:
            raise Unresolvable(f'merged file does not compile: {e}')
    elif path.endswith('.md'):
        new = bad_rows(merged.splitlines()) - bad_rows(u.splitlines()) - bad_rows(o.splitlines())
        if new:
            raise Unresolvable('merged table rows with the wrong column count: ' + '; '.join(sorted(new))[:200])


UNION_MD = re.compile(r'^docs/[^/]+\.md$')
STRUCT = {'catalog.toml': 'toml', 'kit/next_prompt.py': 'py'}


def resolve_file(path, ctx):
    """Resolve one conflicted file in the rebase by the rules; returns how, or raises Unresolvable."""
    stages = {s: show(f':{s}', path) for s in (1, 2, 3)}   # 1 base, 2 upstream (rebase onto), 3 our commit
    if GENERATED.match(path):
        if stages[2] is None:
            raise Unresolvable('build output deleted upstream and changed by us')
        (ROOT / path).write_bytes(stages[2])
        return 'regenerate'
    if None in stages.values():
        raise Unresolvable('one side deleted the file, the other changed it')
    if path == BASELINE:
        try:
            b, u, o = (json.loads(stages[s]) for s in (1, 2, 3))
        except ValueError as e:
            raise Unresolvable(f'does not parse: {e}')
        conflicts = []
        m = json_merge3(b, u, o, [], conflicts)
        if conflicts:
            raise Unresolvable('the same key changed to different values on both sides:\n' + '\n'.join(
                f'    {k}\n      upstream: {uv}\n      ours:     {ov}' for k, uv, ov in conflicts))
        (ROOT / path).write_text(json.dumps(m, indent=1, sort_keys=True) + '\n')
        return 'json-merged'
    try:
        b, u, o = (stages[s].decode('utf-8') for s in (1, 2, 3))
    except UnicodeDecodeError:
        raise Unresolvable('not UTF-8 text')
    if path in KEYED:
        m = ''.join(merge3(*(units(t.splitlines(keepends=True)) for t in (b, u, o)), keyed_resolver(ctx)))
        kind = 'rows merged by id'
    elif path in STRUCT:
        m = structured_merge(b, u, o, STRUCT[path], ctx, path)
        kind = 'literals merged as data' + (', rest by union' if STRUCT[path] == 'toml' else '')
    elif UNION_MD.match(path):
        m = ''.join(merge3(*(t.splitlines(keepends=True) for t in (b, u, o)),
                           union_resolver(ours_first=path in OURS_FIRST)))
        kind = 'union'
    else:
        raise Unresolvable('not a file the script may merge')
    validate(path, m, u, o)
    mlines = collections.Counter(l.strip() for l in m.splitlines())
    for l in u.splitlines():
        if keep(l) and mlines[l.strip()] == 0:
            ctx.superseded.add((path, l.strip()))
    (ROOT / path).write_text(m, encoding='utf-8')
    return kind


def json_merge3(b, u, o, path, conflicts):
    MISSING = object()
    if u == o:
        return u
    if u == b:
        return o
    if o == b:
        return u
    if all(isinstance(x, dict) for x in (b, u, o)):
        res = {}
        for k in sorted(set(b) | set(u) | set(o)):
            v = json_merge3(b.get(k, MISSING), u.get(k, MISSING), o.get(k, MISSING), path + [k], conflicts)
            if v is not MISSING:
                res[k] = v
        return res
    conflicts.append(('/'.join(map(str, path)), u, o))
    return u


def both_sides(path):
    res = []
    for s, name in ((2, 'upstream'), (3, 'ours')):
        t = text(f':{s}', path)
        res.append(f'  --- {name} ({path}) ---')
        res += ['  ' + ln for ln in (t.splitlines()[:40] if t is not None else ['(deleted)'])]
    conflict = git('diff', '--', path, check=False).stdout.splitlines()[:60]
    return res + ['  --- conflict hunks ---'] + ['  ' + ln for ln in conflict]


def rebase_onto(up, build_allowed, ctx):
    """git rebase up, resolving the allowed conflicts by script; returns ({file: how}, regenerate?)."""
    merged, regen = {}, False
    r = git('rebase', '--empty=drop', up, check=False)
    while rebase_dir():
        un = [p for p in git('diff', '--name-only', '-z', '--diff-filter=U').stdout.split('\0') if p]
        if not un:
            staged = git('diff', '--cached', '--quiet', check=False).returncode
            r = git('rebase', '--continue', check=False) if staged else git('rebase', '--skip', check=False)
            if r.returncode and rebase_dir() and not [p for p in git('diff', '--name-only', '--diff-filter=U').stdout.split() if p]:
                git('rebase', '--abort', check=False)
                raise Stop(f'rebase stopped: {r.stderr.strip()[:300]}', 'land again; if it repeats, rebase by hand')
            continue
        stops, details = [], []
        for p in un:
            try:
                how = resolve_file(p, ctx)
            except Unresolvable as e:
                stops.append(f'{p}: {e}')
                details += both_sides(p)
                continue
            if how == 'regenerate':
                regen = True
            merged[p] = how
            git('add', '--', p)
        if regen and not build_allowed and not stops:
            stops.append('build output conflicted; it can only be regenerated with the build check (no --no-build)')
        if stops:
            git('rebase', '--abort', check=False)
            raise Stop('rebase conflict the script may not resolve:\n  ' + '\n  '.join(stops) + '\n' + '\n'.join(details),
                       'make the two changes agree by hand in your clone (keep upstream\'s lines), commit, then land again')
    if r.returncode and not is_ancestor(up, 'HEAD'):
        raise Stop(f'rebase failed: {(r.stderr or r.stdout).strip()[:400]}', 'fix the cause (named above), then land again')
    return merged, regen


# -- derived records: saved row prompts in docs/BACKLOG.md (kit/next_prompt.py)

def record_of(lines, row):
    st = [i for i, ln in enumerate(lines) if ln.startswith(f'| {row} |')]
    if len(st) != 1:
        return None
    i = j = st[0]
    while j < len(lines) - 1 and not lines[j].rstrip().endswith('|'):
        j += 1
    return '\n'.join(lines[i:j + 1])


def generated(tree, row):
    r = run([sys.executable, 'kit/next_prompt.py', '--row', row], cwd=tree, timeout=60)
    return r.stdout[:-1] if r.returncode == 0 and r.stdout.endswith('\n') else None


def supersede_records(up, rws, ctx):
    """A regenerated prompt replaces upstream's record on purpose: its lines count as preserved."""
    ul = (text(up, 'docs/BACKLOG.md') or '').split('\n')
    for rw in rws:
        for l in (record_of(ul, rw) or '').split('\n'):
            if keep(l):
                ctx.superseded.add(('docs/BACKLOG.md', l.strip()))


def resave_prompts(row, lock_row, up, rep, ctx):
    """Re-save a row's prompt cell when it differs from what next_prompt.py prints on the merged tree, only if the cell
    was exactly the generated prompt on upstream's tree (so no hand edit is lost), never for our row or the lock's."""
    np_ = ROOT / 'kit' / 'next_prompt.py'
    if not np_.exists():
        rep['prompts'] = 'kit/next_prompt.py not present: skipped'
        return
    r = run([sys.executable, 'kit/next_prompt.py', '--list'], timeout=60)
    if r.returncode:
        rep['prompts'] = 'next_prompt.py --list failed: skipped'
        return
    rows = [ln.split()[0] for ln in r.stdout.splitlines() if ln.strip()]
    lines = (ROOT / 'docs' / 'BACKLOG.md').read_text(encoding='utf-8').split('\n')
    differ, forced = [], []
    for rw in sorted(ctx.regen_rows - {row, lock_row}):
        g = generated(ROOT, rw)
        if g is not None and record_of(lines, rw):
            rr = run([sys.executable, 'kit/next_prompt.py', '--row', rw, '--save'], timeout=60)
            if rr.returncode == 0:
                forced.append(rw)
    if forced:
        commit_all(f'land {row}: row prompts regenerated after merge ({", ".join(forced)})')
        lines = (ROOT / 'docs' / 'BACKLOG.md').read_text(encoding='utf-8').split('\n')
    for rw in rows:
        if rw in (row, lock_row) or rw in forced:
            continue
        rec = record_of(lines, rw)
        g = generated(ROOT, rw) if rec else None
        if rec and g is not None and rec != ' | '.join(lines[lines.index(rec.split('\n')[0])].split(' | ')[:3]) + ' | ' + g + ' |':
            differ.append((rw, rec))
    if not differ:
        supersede_records(up, forced, ctx)
        rep['prompts'] = (f'regenerated {", ".join(forced)}; ' if forced else '') + 'saved prompts match next_prompt.py'
        return
    wt = pathlib.Path(f'/tmp/land-wt-{os.getpid()}')
    saved, left = [], []
    try:
        git('worktree', 'add', '-q', '--detach', str(wt), up)
        up_lines = (wt / 'docs' / 'BACKLOG.md').read_text(encoding='utf-8').split('\n')
        for rw, rec in differ:
            gu, urec = generated(wt, rw), record_of(up_lines, rw)
            if gu is not None and urec is not None and urec.split(' | ', 3)[-1] == gu + ' |' and rec == urec:
                rr = run([sys.executable, 'kit/next_prompt.py', '--row', rw, '--save'], timeout=60)
                (saved if rr.returncode == 0 else left).append(rw)
            else:
                left.append(rw)
    finally:
        git('worktree', 'remove', '--force', str(wt), check=False)
    if saved:
        commit_all(f'land {row}: row prompts re-saved after merge ({", ".join(saved)})')
    supersede_records(up, forced + saved, ctx)
    rep['prompts'] = (f'regenerated {", ".join(forced)}; ' if forced else '') + (f're-saved {", ".join(saved)}' if saved else 'none re-saved') + (
        f'; differ but hold hand edits, left for a human: {", ".join(left)}' if left else '')


# ---------------------------------------------------------------- preservation

def keep(line):
    return len(line.strip()) >= MIN_LINE


def counts(t):
    return collections.Counter(l.strip() for l in t.splitlines() if keep(l)) if t is not None else collections.Counter()


def preservation(start, up, head, drops, auto=frozenset()):
    """Every line upstream added in start..up is in the same file in head; every file it added or renamed exists."""
    res = {'checked': 0, 'review': [], 'accepted': [], 'auto': [], 'missing': [], 'gone': [], 'files': 0}
    for st, old, new in name_status(start, up):
        if new == LOCK or old == LOCK:
            continue
        if st in 'ARC' and git('cat-file', '-e', f'{head}:{new}', check=False).returncode:
            res['gone'].append(f'{new} (upstream {"added" if st != "R" else "renamed it from " + old}) is not in HEAD')
            continue
        if st not in 'AMRC' or GENERATED.match(new) or new == BASELINE:
            continue
        U = counts(text(up, new))
        S = counts(text(start, old)) if st in 'MR' else collections.Counter()
        H = counts(text(head, new))
        res['files'] += 1
        for line, a in (U - S).items():
            res['checked'] += a
            miss = min(a, U[line] - H[line])
            if miss <= 0:
                continue
            item = f'{new}: {line[:160]}' + (f' (x{miss})' if miss > 1 else '')
            if (new, line) in drops:
                res['accepted'].append(item)
            elif (new, line) in auto:
                res['auto'].append(item)
            elif S[line] > 0:
                res['review'].append(item)
            else:
                res['missing'].append(item)
    return res


def baseline_keys(rev):
    t = text(rev, BASELINE)
    try:
        return {(e, p): h for e, m in json.loads(t)['editions'].items() for p, h in m.items()} if t else {}
    except (ValueError, KeyError, AttributeError):
        return None


def diff_keys(a, b):
    return {k for k in a.keys() | b.keys() if a.get(k) != b.get(k)}


# ---------------------------------------------------------------- the steps under the lock

def run(cmd, timeout=None, cwd=None):
    return subprocess.run(cmd, cwd=cwd or ROOT, capture_output=True, text=True, timeout=timeout)


def norm_out(p):
    p = p.strip()
    m = re.match(r'^[\w.-]+: (?:added|removed|changed) (.+)$', p)
    if m:
        p = m.group(1)
    if p.startswith('kit/'):
        return p[4:]
    if p.startswith(('courses/', 'docs/', 'design/', 'brands/', 'editions/')):
        return '../' + p
    return p


def read_expected(path):
    paths, drops = set(), set()
    if not path:
        return paths, drops
    for ln in pathlib.Path(path).read_text(encoding='utf-8').splitlines():
        s = ln.strip()
        if not s or s.startswith('#'):
            continue
        if s.startswith('drop:'):
            f, _, line = s[5:].partition(' :: ')
            drops.add((f.strip(), line.strip()))
        else:
            paths.add(norm_out(s))
    return paths, drops


def baseline_check():
    r = run([sys.executable, 'baseline.py', '--check'], cwd=ROOT / 'kit')
    diff = [(m.group(1), m.group(2), m.group(3)) for m in
            re.finditer(r'^([\w.-]+): (added|removed|changed) (.+)$', r.stdout, re.M)]
    if r.returncode not in (0, 1) or 'baseline:' not in r.stdout:
        raise Stop('baseline.py --check failed to run:\n' + (r.stdout + r.stderr)[-1500:], 'fix the build, then land again')
    return diff


def commit_all(msg):
    git('add', '-u')
    unt = [p for p in git('ls-files', '-o', '--exclude-standard', '-z').stdout.split('\0') if p and GENERATED.match(p)]
    if unt:
        git('add', '--', *unt)
    if git('diff', '--cached', '--quiet', check=False).returncode:
        git('commit', '-q', '--no-verify', '-m', msg)
        return True
    return False


def integrate(row, start, up, o, expected, drops, rep, ctx, lock_row):
    """Rebase on up and run every check; leaves HEAD ready to push or raises Stop."""
    if not is_ancestor(up, 'HEAD'):
        merged, regen = rebase_onto(up, not o.no_build, ctx)
        rep['merged'].update(merged)
        rep['regen'] = rep['regen'] or regen
        if merged:
            resave_prompts(row, lock_row, up, rep, ctx)
    ours = changed(up, 'HEAD')
    if LOCK in ours:
        raise Stop(f'our commits touch {LOCK}', f'remove {LOCK} from your commits, then land again')
    # deletions of ours that upstream changed
    up_mod = {n for s, _, n in name_status(start, up) if s in 'MR'} | {old for s, old, _ in name_status(start, up) if s == 'R'}
    bad = sorted(p for s, p, _ in name_status(up, 'HEAD') if s == 'D' and p in up_mod)
    if bad:
        raise Stop('files we deleted were changed upstream since our start:\n  ' + '\n  '.join(bad),
                   'restore them (keep upstream\'s version) or agree the deletion with the row that changed them')
    # markers
    mk = marker_files(changed(start, 'HEAD') or None) if changed(start, 'HEAD') else []
    if mk:
        raise Stop('conflict markers after the rebase in:\n  ' + '\n  '.join(mk), 'remove them by hand, commit, land again')
    # preservation
    pv = preservation(start, up, 'HEAD', drops, ctx.superseded)
    rep['preserved'] = pv
    fails = pv['missing'] + pv['gone']
    bk_up, bk_start, bk_head = baseline_keys(up), baseline_keys(start), baseline_keys('HEAD')
    if bk_head is None:
        raise Stop(f'{BASELINE} does not parse in HEAD', 'fix it by hand, land again')
    rerecorded = any(s.split(' ', 1)[1].startswith(f'land {row}: baseline re-recorded') for s in subjects(up, 'HEAD'))
    if bk_up is not None and bk_start is not None and not rerecorded:
        for k in sorted(diff_keys(bk_start, bk_up)):
            if bk_head.get(k) != bk_up.get(k):
                fails.append(f'{BASELINE}: {k[0]} {k[1]} upstream {str(bk_up.get(k))[:12]}, HEAD {str(bk_head.get(k))[:12]}')
    if fails:
        raise Stop('PRESERVATION CHECK FAILED: upstream work since our start is missing from HEAD:\n  ' + '\n  '.join(fails),
                   'your commits (or a conflict you resolved by hand) dropped it: restore those lines; if a removal is '
                   'deliberate, list it in --expected as "drop: <path> :: <line>"; then land again')
    # sanity: JSON and TOML touched by either side
    for p in changed(start, 'HEAD'):
        if p.endswith(('.json', '.toml')) and p != LOCK:
            t = text('HEAD', p)
            if t is None:
                continue
            try:
                json.loads(t) if p.endswith('.json') else tomllib.loads(t)
            except (ValueError, tomllib.TOMLDecodeError) as e:
                raise Stop(f'{p} does not parse after the rebase: {e}', 'fix it, commit, land again')
    if (ROOT / 'kit' / 'index_check.py').exists():
        try:
            r = run([sys.executable, 'kit/index_check.py'], timeout=300)
        except subprocess.TimeoutExpired:
            r = None
        if r is None:
            rep['index'] = 'timed out (skipped)'
        elif r.returncode:
            raise Stop('index_check fails on the combined tree:\n' + (r.stdout + r.stderr)[-1500:],
                       'fix docs/courses-index.md (or the source it names), commit, land again')
        else:
            rep['index'] = 'ok'
    # build check: only when our commits change something the build reads, or build output had to be regenerated
    build_paths = [p for p in ours if not NOBUILD.match(p)]
    if build_paths or rep['regen']:
        if o.no_build:
            rep['baseline'] = 'skipped (--no-build)'
        else:
            say(f'build check: baseline.py --check ({len(build_paths)} build-relevant paths changed by us)')
            diff = baseline_check()
            declared_up = {p for _, p in diff_keys(bk_start or {}, bk_up or {})}
            undeclared = sorted(f'{e}: {t} {p}' for e, t, p in diff if p not in expected and p not in declared_up)
            if undeclared:
                git('reset', '-q', '--hard', 'HEAD')
                raise Stop('output changed by the combination, not declared by anyone:\n  ' + '\n  '.join(undeclared),
                           'if these are your row\'s expected differences add them to --expected; otherwise find which '
                           'change produced them; then land again')
            if diff:
                say(f'{len(diff)} expected differences: re-recording kit/baseline.json')
                r = run([sys.executable, 'baseline.py'], cwd=ROOT / 'kit')
                if r.returncode:
                    raise Stop('baseline.py failed:\n' + (r.stdout + r.stderr)[-1500:], 'fix the build, then land again')
                commit_all(f'land {row}: baseline re-recorded for expected differences')
                if baseline_check():
                    raise Stop('baseline.py --check is not clean after re-recording', 'the build is not deterministic: investigate')
                rep['baseline'] = f're-recorded ({len(diff)} expected differences), then clean'
            else:
                rep['baseline'] = 'clean'
            commit_all(f'land {row}: build output after rebase')
    else:
        rep['baseline'] = 'not needed (no build-relevant change of ours)'
    if o.no_verify:
        rep['verify'] = 'skipped (--no-verify)'
    else:
        say('verify.py (scoped)')
        r = run([sys.executable, 'verify.py'], cwd=ROOT / 'kit')
        if r.returncode or 'ALL CHECKS PASSED' not in r.stdout:
            git('reset', '-q', '--hard', 'HEAD')
            raise Stop('verify.py did not pass on the combined tree:\n' + (r.stdout + r.stderr)[-2000:],
                       'fix what it names, commit, land again')
        commit_all(f'land {row}: verify record')
        rep['verify'] = 'ALL CHECKS PASSED'
    if git('status', '--porcelain', '--untracked-files=no').stdout.strip():
        commit_all(f'land {row}: build output after rebase')


